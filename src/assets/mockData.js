export const getMockArtistDetails = (artistId) => {
  const song = MOCK_SONGS.find((s) => s.artists[0]?.adamid === artistId) || MOCK_SONGS[0];
  return {
    artists: {
      [artistId || "1001"]: {
        attributes: {
          name: song.subtitle,
          genreNames: [song.genres.primary],
          artwork: {
            url: song.images.coverart,
          },
        },
      },
    },
    songs: {
      [song.key]: song,
      ...MOCK_SONGS.reduce((acc, s) => {
        acc[s.key] = s;
        return acc;
      }, {}),
    },
  };
};
